"""Build the friend-safe Jarvis installer.

    .venv\\Scripts\\python.exe tools\\build_installer.py            # freeze + scan + MSI
    .venv\\Scripts\\python.exe tools\\build_installer.py --freeze   # only the frozen app (dist\\Jarvis)
    .venv\\Scripts\\python.exe tools\\build_installer.py --msi      # only the MSI from an existing dist\\Jarvis

Steps (any failure stops the build):
  1. leak-scan the source files that would ship (tools/leak_scan.py)
  2. freeze with PyInstaller from an ALLOW-LIST (the same list the leak scanner uses): Jarvis.exe (the app)
     and jarvis-python.exe (runs helper scripts), side by side in dist\\Jarvis
  3. leak-scan everything in dist\\Jarvis, including the compressed Python archive inside the .exe files
  4. build dist\\Jarvis-<version>.msi with the WiX Toolset (per-user install, no admin needed)
"""

from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from core.brand import APP_NAME, COPYRIGHT, DEVELOPER_NAME  # noqa: E402
from tools import leak_scan  # noqa: E402

DIST = ROOT / "dist"
BUILD = ROOT / "build"
APP_DIR = DIST / APP_NAME
VERSION = "1.0.0"

OUR_PACKAGES = ["actions", "agent", "auth", "core", "dashboard", "gui", "jarvis_connect", "smart_home",
                "plugins", "memory", "config"]
OUR_MODULES = ["ui", "updater", "discord_bot", "groq_client", "key_manager", "llm_client", "or_client",
               "plugin_manager", "workspace_store", "gesture_utils", "smart_home_page_new"]
THIRD_PARTY_SUBMODULES = ["uvicorn", "google.genai", "edge_tts", "kasa", "instagrapi", "discord",
                          "pywinauto", "comtypes", "win32com", "duckduckgo_search", "groq", "fastapi",
                          "youtube_transcript_api", "pycaw"]
THIRD_PARTY_DATA = ["mediapipe", "certifi", "edge_tts", "duckduckgo_search", "playwright"]
# what helper scripts / skills may import in jarvis-python.exe
HELPER_IMPORTS = ["requests", "bs4", "json", "csv", "sqlite3", "openpyxl", "docx", "pptx", "PIL", "reportlab",
                  "numpy", "psutil", "http.server", "urllib.request", "xml.etree.ElementTree",
                  "core.skill_forge.sandbox_runner"]


def step(msg: str) -> None:
    print(f"\n=== {msg} ===", flush=True)


def scan_source() -> None:
    step("1/4 Leak scan of the files that will ship")
    if leak_scan.main(["leak_scan"]) != 0:
        sys.exit("Build stopped: the leak scanner found personal data in the source. Fix it first.")


def write_spec() -> Path:
    files = leak_scan.shipped_files(ROOT)
    datas = []
    for p in files:
        rel = p.relative_to(ROOT)
        if rel.parts[0] == "tools" or p.name in ("requirements.txt", "version.txt"):
            continue
        if p.suffix == ".py" and p.name != "sandbox_runner.py":
            continue                       # code goes in compiled; sandbox_runner must exist as a file
        datas.append((str(p), str(rel.parent) if str(rel.parent) != "." else "."))
    spec = f'''# Generated by tools/build_installer.py. Do not edit by hand.
import sys
from PyInstaller.utils.hooks import collect_submodules, collect_data_files
sys.path.insert(0, {str(ROOT)!r})

hidden = []
for pkg in {OUR_PACKAGES!r}:
    hidden += collect_submodules(pkg)
hidden += {OUR_MODULES!r}
for pkg in {THIRD_PARTY_SUBMODULES!r}:
    try:
        hidden += collect_submodules(pkg)
    except Exception:
        pass
# numpy 2.x loads some private modules from C code; PyInstaller can't see those imports
NUMPY = collect_submodules("numpy", filter=lambda n: ".tests" not in n and "f2py" not in n and "distutils" not in n)
hidden += NUMPY
datas = {datas!r}
for pkg in {THIRD_PARTY_DATA!r}:
    try:
        datas += collect_data_files(pkg)
    except Exception:
        pass

a = Analysis([{str(ROOT / "main.py")!r}], pathex=[{str(ROOT)!r}], datas=datas, hiddenimports=hidden,
             excludes=["pytest", "tests", "tools", "IPython", "jupyter", "notebook"], noarchive=False)
pyz = PYZ(a.pure)
app = EXE(pyz, a.scripts, [], exclude_binaries=True, name={APP_NAME!r}, console=False,
          icon={str(ROOT / "assets" / "Jarvis_Lite_Logo.ico")!r}, version={str(ROOT / "version.txt")!r},
          upx=False, contents_directory=".")

b = Analysis([{str(ROOT / "jarvis_python.py")!r}], pathex=[{str(ROOT)!r}], hiddenimports={HELPER_IMPORTS!r} + NUMPY,
             excludes=["pytest", "tests", "tools", "PyQt6"], noarchive=False)
pyz_b = PYZ(b.pure)
helper = EXE(pyz_b, b.scripts, [], exclude_binaries=True, name="jarvis-python", console=True,
             icon={str(ROOT / "assets" / "Jarvis_Lite_Logo.ico")!r}, version={str(ROOT / "version.txt")!r},
             upx=False, contents_directory=".")

coll = COLLECT(app, a.binaries, a.datas, helper, b.binaries, b.datas, upx=False, name={APP_NAME!r})
'''
    BUILD.mkdir(exist_ok=True)
    path = BUILD / "jarvis.spec"
    path.write_text(spec, encoding="utf-8")
    return path


def freeze() -> None:
    step("2/4 Freezing Jarvis with PyInstaller (this takes several minutes)")
    spec = write_spec()
    if APP_DIR.exists():
        shutil.rmtree(APP_DIR)
    env = dict(os.environ, JARVIS_SECRETS_MIGRATE="0")
    r = subprocess.run([sys.executable, "-m", "PyInstaller", "--noconfirm", "--clean",
                        "--distpath", str(DIST), "--workpath", str(BUILD / "work"), str(spec)], cwd=ROOT, env=env)
    if r.returncode != 0 or not (APP_DIR / f"{APP_NAME}.exe").exists():
        sys.exit("Build stopped: PyInstaller failed (see the output above).")


def scan_dist() -> None:
    step("3/4 Leak scan of the built app (including the code inside the .exe files)")
    if leak_scan.main(["leak_scan", str(APP_DIR)]) != 0:
        sys.exit("Build stopped: personal data was found in the built app. Nothing was packaged.")


def build_msi() -> Path:
    step("4/4 Building the MSI with WiX")
    from tools import wix_msi
    out = wix_msi.build(APP_DIR, DIST, version=VERSION, publisher=DEVELOPER_NAME, copyright_text=COPYRIGHT)
    print(f"MSI ready: {out}  ({out.stat().st_size / 1e6:.0f} MB)")
    return out


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--freeze", action="store_true", help="only build dist\\Jarvis")
    ap.add_argument("--msi", action="store_true", help="only build the MSI from dist\\Jarvis")
    args = ap.parse_args()
    if not args.msi:
        scan_source()
        freeze()
        scan_dist()
    if not args.freeze:
        if not APP_DIR.exists():
            sys.exit("dist\\Jarvis doesn't exist yet: run without --msi first.")
        build_msi()


if __name__ == "__main__":
    main()
